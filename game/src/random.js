// Emberlight — a tiny seeded random generator so screenshot scenes are
// reproducible: the same seed always deals the same night.
export function makeRandom(seed) {
  let state = (seed >>> 0) || 1;
  return {
    next() {
      state ^= state << 13;
      state ^= state >>> 17;
      state ^= state << 5;
      state >>>= 0;
      return state / 4294967296;
    },
    range(min, max) {
      return min + this.next() * (max - min);
    },
    pick(list) {
      return list[Math.floor(this.next() * list.length)];
    },
  };
}
